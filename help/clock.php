  <div class="justify">
    <h1>Timer <span class="object">display</span></h1>
    Counts elapsed time. The Start button starts or pauses the timer. Reset returns it to zero.
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help">
    <use href="/icons.svg?v=<?php echo filemtime($_SERVER['DOCUMENT_ROOT'] . '/icons.svg'); ?>#countdown"></use>
  </svg>
  <div class="justify">
    <h1>Countdown <span class="object">display</span></h1>
    Counts down from the Hours, Minutes and Seconds fields. The corresponding knobs adjust these values. The Start button starts or pauses the countdown. <span class="default">Default: 1 minute.</span>
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help">
    <use href="/icons.svg#bell"></use>
  </svg>
  <div class="justify">
    <h1>Alarm <span class="object">button</span></h1>
    Toggles a repeating alert when Countdown finishes. The alert flashes until Alarm is turned off, Countdown is restarted, its duration is changed or Reset is pressed. Sound must be on for the alert to be audible. <span class="default">Default: off.</span>
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help">
    <use href="/icons.svg#decimals"></use>
  </svg>
  <div class="justify">
    <h1>ms <span class="object">button</span></h1>
    Toggles milliseconds in the Timer or Countdown display. Each has its own setting. When hidden, elapsed time is rounded down and remaining time is rounded up to the next second. <span class="default">Default: on.</span>
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help">
    <use href="/icons.svg#clock"></use>
  </svg>
  <div class="justify">
    <h1>Clock <span class="object">display</span></h1>
    Shows local time in analog and digital form, with hours, minutes and seconds.
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help">
    <use href="/icons.svg#calendar"></use>
  </svg>
  <div class="justify">
    <h1>Calendar <span class="object">display</span></h1>
    Shows the current month, weekday names and week numbers. Weeks start on Monday, and today is highlighted.
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help">
    <use href="/icons.svg#sound"></use>
  </svg>
  <div class="justify">
    <h1>Sound <span class="object">button</span></h1>
    Toggles ticks for the selected Clock, Timer or Countdown tab. Timer and Countdown tick while running. Countdown also sounds when it finishes, even if another tab is selected. Each tab has its own setting. Calendar has no sound. <span class="default">Default: off.</span>
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help">
    <use href="/icons.svg#haptic"></use>
  </svg>
  <div class="justify">
    <h1>Haptic <span class="object">button</span></h1>
    Toggles feedback for the selected Clock, Timer or Countdown tab on supported devices. Timer and Countdown provide feedback while running. Countdown also provides feedback when it finishes, even if another tab is selected. Each tab has its own setting. Calendar has no feedback. <span class="default">Default: off.</span>
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help">
    <use href="/icons.svg#reset"></use>
  </svg>
  <div class="justify">
    <h1>Reset <span class="object">button</span></h1>
    Stops Timer and Countdown, returns to Clock and restores all Clock options to their defaults.
  </div>
</div>