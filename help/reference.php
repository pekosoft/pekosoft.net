  <div class="justify">
    <h1>Instrument <span class="object">module</span></h1>
    A full-width scrollable result view that changes by selected mode. Supports standard view and cards view. BPM lists 1 to 300 with writing, parity, half and double values. Tempi lists the 11 Italian tempo names and BPM ranges used by Metronome. Notes lists chromatic notes from A0 to C8 with Helmholtz octave and register names, MIDI (Musical Instrument Digital Interface) note numbers and frequency data. Scales lists common scale formulas and C examples. Chords lists common chord formulas, semitone stacks and C examples. Prefixes lists all 24 SI prefixes with their symbols, powers of ten, exact decimal multipliers and English short-scale names, plus the unprefixed unit.
  </div>
</div>

