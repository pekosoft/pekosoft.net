    <h1>Prefixes <span class="object">button</span></h1>
    Selects Metric prefixes mode, from quecto (10<sup>-30</sup>) to quetta (10<sup>30</sup>). Prefix names open Wikipedia articles. The No prefix row represents the unprefixed unit (10<sup>0</sup>). Prefix symbols are case-sensitive: m means milli, while M means mega. These are decimal SI prefixes, not binary prefixes. Writing uses English short-scale names, where billion means 10<sup>9</sup> and trillion means 10<sup>12</sup>. Fractions use names such as Thousandth and Millionth. Sort orders the rows by multiplier. Cards support copying the enabled information without a sound preview.
  </div>
</div>

