  <div class="justify">
    <h1>Cables <span class="object">button</span></h1>
    Selects Cables mode. Compares USB (Universal Serial Bus), HDMI (High-Definition Multimedia Interface), DisplayPort, Thunderbolt, Ethernet, analog and digital audio, speaker cables, MIDI (Musical Instrument Digital Interface), SDI (Serial Digital Interface), legacy video and storage connections. Separate rows distinguish published interface revisions, cable certifications, connectors and wiring formats.
    The 19 columns begin with connector pictograms and cable name, followed by family, version, year, connectors, contacts, signal, rate, video, audio, power, length, impedance, shielding, compatibility, notes, source links and Developer. Developer links identify originators or organizations responsible for the specifications. No single developer indicates a general cable or wiring convention rather than one organization's interface. Pictograms identify the connector types listed for each row. Multiple pictograms indicate alternatives or the ends of an adapter cable. They are simplified identifiers, not wiring diagrams. Scroll horizontally to reach additional columns or use the Column buttons to hide information in both views. Cards support copying all enabled text without a sound preview.
    Rates are nominal signaling or link rates, not guaranteed file-transfer speeds. Video formats are examples, not universal maximum resolutions. DSC (Display Stream Compression), bit depth, chroma sampling and endpoint support affect video formats. Power and reach require appropriately rated cables and equipment. A connector shape or version number alone does not guarantee every listed capability. Not specified means that no single value is given, not zero.
    The reference covers the listed published revisions through USB4 2.0, USB Power Delivery 3.2, HDMI 2.2, DisplayPort 2.1b and Thunderbolt 5. It is not an exhaustive list of proprietary pinouts or every amendment to every cabling standard. Source links provide further details.
  </div>
